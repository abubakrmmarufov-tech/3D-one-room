import {readFileSync,existsSync,writeFileSync,mkdirSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';

const checks=[];
const check=(name,pass,details)=>checks.push({name,pass,details});
const html=readFileSync('Shakhrofar.html','utf8');
const plan=readFileSync('public/assets/residence-plan.svg','utf8');
const modules=[...html.matchAll(/<script type="module">([\s\S]*?)<\/script>/g)];
check('one embedded application module',modules.length===1);
const parsed=spawnSync(process.execPath,['--check','--input-type=module'],{input:modules[0]?.[1]||'',encoding:'utf8'});
check('embedded JavaScript parses',parsed.status===0,parsed.stderr||undefined);
const markup=html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g,'');
const references=[...markup.matchAll(/\b(?:src|href)="([^"]+)"/g)].map(m=>m[1]);
check('all standalone markup assets are embedded',references.every(r=>r.startsWith('data:')||r.startsWith('#')),references.filter(r=>!r.startsWith('data:')&&!r.startsWith('#')));
const encoded=Buffer.from(plan).toString('base64');
check('standalone embeds the exact generated plan',html.includes('window.__PLAN_DATA__="data:image/svg+xml;base64,'+encoded+'"'));
check('no-JavaScript drawing is embedded',/<noscript>[\s\S]*?src="data:image\/svg\+xml;base64,/.test(html));
check('standalone includes Three.js license',html.includes('Copyright © 2010-2026 three.js authors')&&html.includes('Permission is hereby granted'));
const dist=readFileSync('dist/index.html','utf8');
const distRefs=[...dist.matchAll(/\b(?:src|href)="([^"]+)"/g)].map(m=>m[1]).filter(r=>!r.startsWith('#')&&!r.startsWith('data:'));
check('every distribution markup asset exists',distRefs.every(r=>!r.startsWith('/')&&existsSync('dist/'+r.replace(/^\.\//,''))),distRefs);
check('source contains all five room controls',[1,2,3,4,5].every(i=>html.includes(`data-room="${i}"`)));
const pkg=JSON.parse(readFileSync('package.json','utf8'));
check('production Three.js version is pinned',pkg.dependencies.three==='0.183.2');
const assets=JSON.parse(readFileSync('docs/material-assets.json','utf8')).assets;
check('all eleven sourced PBR maps match source pins',assets.length===11&&assets.every(a=>existsSync(a.path)&&createHash('sha256').update(readFileSync(a.path)).digest('hex')===a.sha256));
check('offline embeds every PBR map',assets.every(a=>html.includes('data:image/jpeg;base64,'+readFileSync(a.path).toString('base64'))));
const files=['Shakhrofar.html','dist/index.html','public/assets/residence-plan.svg'];
const manifest=files.map(path=>{const data=readFileSync(path);return{path,bytes:data.length,sha256:createHash('sha256').update(data).digest('hex')};});
const report={scope:'Static packaging and JavaScript syntax only. No browser, GPU, interaction, network, or visual verification.',checks,manifest};
mkdirSync('docs/qa',{recursive:true});writeFileSync('docs/qa/package-report.json',JSON.stringify(report,null,2));
console.log(JSON.stringify({checks:checks.length,failed:checks.filter(c=>!c.pass),manifest},null,2));
if(checks.some(c=>!c.pass))process.exitCode=1;
